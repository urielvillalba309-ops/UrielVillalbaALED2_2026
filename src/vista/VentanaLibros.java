    public int getIdSeleccionado() {
        int fila = tablaLibros.getSelectedRow();
        return (fila == -1) ? -1 : (int) tablaLibros.getValueAt(fila, 0);
    }

    public void mostrarLibros(List<Libro> libros) {
        DefaultTableModel modelo = (DefaultTableModel) tablaLibros.getModel();
        modelo.setRowCount(0);
        for (Libro l : libros) {
            modelo.addRow(new Object[]{
                l.getId(), l.getTitulo(), l.getAutor(),
                l.getCategoria(), l.getEditorial(), l.getStock()
            });
        }
    }

    
    private void cargarFormularioDesdeFila() {
        int fila = tablaLibros.getSelectedRow();
        if (fila == -1) return;
        JTextField[] campos = campos();
        for (int i = 0; i < campos.length; i++) {
            campos[i].setText(tablaLibros.getValueAt(fila, i + 1).toString());
        }
    }

    public void limpiarFormulario() {
        for (JTextField campo : campos()) {
            campo.setText("");
        }
        tablaLibros.clearSelection();
        txtTitulo.requestFocus();
    }

    public void mostrarMensaje(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje);
    }

    public boolean confirmar(String mensaje) {
        return JOptionPane.showConfirmDialog(this, mensaje, "Confirmar",
                JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION;
    }

